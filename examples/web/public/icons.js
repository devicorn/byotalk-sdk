/** An <svg> element for icon `name`. */
export function icon(name, size = 20) {
  const span = document.createElement("span");
  span.className = "icon";
  span.setAttribute("aria-hidden", "true");
  span.innerHTML = `<svg xmlns="http://www.w3.org/2000/svg" width="${size}" height="${size}" viewBox="0 0 24 24" fill="none" stroke="currentColor" stroke-width="2" stroke-linecap="round" stroke-linejoin="round">${P[name] ?? ""}</svg>`;
  return span;
}

/** Replaces the content of every [data-icon] element with its icon (static markup in index.html). */
export function hydrateIcons(root = document) {
  for (const n of root.querySelectorAll("[data-icon]")) n.prepend(icon(n.dataset.icon, Number(n.dataset.size) || 20));
}

const COLORS = ["#6366f1", "#0ea5e9", "#10b981", "#f59e0b", "#ef4444", "#8b5cf6", "#ec4899", "#14b8a6", "#f97316", "#64748b"];

/** Round avatar with initials and a stable color per id. */
export function avatar(id, label, size = 40, group = false) {
  const a = document.createElement("span");
  a.className = "avatar";
  a.style.setProperty("--size", `${size}px`);
  let h = 0;
  for (const ch of id) h = (h * 31 + ch.charCodeAt(0)) >>> 0;
  a.style.background = COLORS[h % COLORS.length];
  if (group) a.append(icon("users", Math.round(size * 0.45)));
  else a.textContent = (label || id).split(/\s+/).map((w) => w[0]).join("").slice(0, 2).toUpperCase();
  return a;
}
